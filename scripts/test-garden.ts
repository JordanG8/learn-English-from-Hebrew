import assert from "node:assert/strict";
import { answerGarden, claimGift, coerceGarden, completeMission, dueQuestions, freshGarden, placeGift, retainedWords } from "@/lib/garden/progress";
import { MISSIONS, QUESTIONS } from "@/lib/garden/curriculum";
let p = freshGarden();
assert.deepEqual(coerceGarden(null), p);
assert.deepEqual(coerceGarden({ earned: ["fake", 3], gifts: ["flowers"], placed: {flowers: 9} }), p);
assert.equal(completeMission(p, "hello").completed.length, 0);
assert.equal(claimGift(p, "flowers").gifts.length, 0);
p = answerGarden(p,"hello-1",false,true,false,"2026-10-21");
assert.equal(p.earned.length, 0);
p = answerGarden(p,"hello-1",true,false,false,"2026-10-21");
assert.equal(p.earned.length, 1, "successful retry earns a star");
assert.equal(p.evidence["hello-1"].independentDays.length, 0, "assisted answers aren't independent evidence");
p = answerGarden(p,"hello-1",true,true,false,"2026-10-21");
assert.equal(p.earned.length, 1, "replays don't farm stars");
assert.equal(dueQuestions(p,"2026-10-21").length, 0);
for(const q of QUESTIONS) p=answerGarden(p,q.id,true,true,false,"2026-10-21");
assert.equal(p.earned.length,9);
for(const m of MISSIONS) p=completeMission(p,m.id);
assert.equal(p.completed.length,3);
for(const id of ["flowers","ball","house","kite"])p=claimGift(p,id);
assert.equal(p.gifts.length,3,"cannot overspend reward entitlement");
p=claimGift(p,"flowers");assert.equal(p.gifts.length,3);
p=placeGift(p,"flowers",0);p=placeGift(p,"ball",0);
assert.deepEqual(p.placed,{ball:0},"replacement retains ownership but frees placement");
p=placeGift(p,"house",3);assert.deepEqual(p.placed,{ball:0});
assert.deepEqual(coerceGarden(JSON.parse(JSON.stringify(p))),p,"round trip preserves progress");
assert.equal(retainedWords(p),false);
const review=dueQuestions(p,"2026-10-22");assert.equal(review.length,3);
for(const q of review)p=answerGarden(p,q.id,true,true,true,"2026-10-22");
assert.equal(p.earned.length,12);
assert.equal(dueQuestions(p,"2026-10-22").length,0,"daily review capped at three rewards");
assert.deepEqual(dueQuestions(p,"2026-10-23").map(q=>q.id),["friends-1","friends-2","friends-3"],"oldest items get reviewed so early questions cannot starve later words");
p=answerGarden(p,review[0].id,true,true,true,"2026-10-22");assert.equal(p.earned.length,12);
for(const id of ["friends-1","friends-2","friends-3"])p=answerGarden(p,id,true,true,false,"2026-10-23");
assert.equal(retainedWords(p),true,"badge requires independent recall on different days");
for(const m of MISSIONS){const taught=new Set<string>();for(const s of m.steps){if(s.kind==="teach")taught.add(s.cue);else {assert.ok(taught.has(s.cue),`${s.id}: target taught before testing`);for(const o of s.options??[])assert.ok(taught.has(o),`${s.id}: option taught before testing`);}}}
console.log("Garden checks passed: safe load, earned rewards, retry credit, duplicate prevention, gift limits, placement, persistence, delayed review, mastery, and curriculum prerequisites.");
